    private void jButtonAddActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonAddActionPerformed
        // TODO add your handling code here:
        String nama = jInputNama.getText();
        if (!nama.isEmpty()) {
            Mahasiswa mhs = new Mahasiswa(nama);
            mhsService.add(mhs);
            jInputNama.setText("");
            loadDataToComponent();
        }
    }//GEN-LAST:event_jButtonAddActionPerformed

    private void jButtonEditActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonEditActionPerformed
        // TODO add your handling code here:
        Integer id = Integer.parseInt(jInputEditID.getText());
        String nama = jInputEditNama.getText();
        Mahasiswa mhs = new Mahasiswa(id, nama);
        jInputEditID.setText("");
        jInputEditNama.setText("");
        mhsService.update(mhs);
        loadDataToComponent();
        
    }//GEN-LAST:event_jButtonEditActionPerformed

