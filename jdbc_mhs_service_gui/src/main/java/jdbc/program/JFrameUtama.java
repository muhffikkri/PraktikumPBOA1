    private void loadDataToComponent() {
        modelID.clear();
        modelNama.clear();
        
        // Mengambil list mahasiswa dari database via service
        List<Mahasiswa> listMhs = mhsService.getAll();
        for (Mahasiswa mhs : listMhs) {
            modelID.addElement(mhs.getId());
            modelNama.addElement(mhs.getNama());
        }
    }
    
